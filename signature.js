  async function loadFontAndGetPaths(options) {
    options = options || {};
    var text = options.text || 'Rahul Achari YC';
    var fontSize = options.fontSize || 21;
    var fontUrl = options.fontUrl;

    var fontPaths = fontUrl 
      ? [fontUrl] 
      : [
          '/LastoriaBoldRegular.otf',
          './LastoriaBoldRegular.otf',
          '/components/LastoriaBoldRegular.otf',
          'https://www.componentry.fun/LastoriaBoldRegular.otf'
        ];

    var font = null;
    var opentypeLib = (typeof window !== 'undefined' && window.opentype) ? window.opentype : null;

    if (opentypeLib) {
      for (var i = 0; i < fontPaths.length; i++) {
        var path = fontPaths[i];
        try {
          if (typeof opentypeLib.load === 'function') {
            font = await new Promise(function(resolve, reject) {
              opentypeLib.load(path, function(err, f) {
                if (err || !f) reject(err);
                else resolve(f);
              });
            });
          }
          if (!font && typeof opentypeLib.parse === 'function' && typeof fetch === 'function') {
            var res = await fetch(path);
            if (res.ok) {
              var buf = await res.arrayBuffer();
              font = opentypeLib.parse(buf);
            }
          }
          if (font) break;
        } catch (e) {
          // try next path
        }
      }
    }

    if (!font) {
      if (text === 'Rahul Achari YC' && fontSize === 21) {
        return DEFAULT_SIGNATURE_DATA;
      }
      return {
        width: Math.ceil(text.length * fontSize * 0.6),
        height: Math.ceil(fontSize * 3),
        fontSize: fontSize,
        paths: text === 'Rahul Achari YC' ? DEFAULT_SIGNATURE_DATA.paths : []
      };
    }

    var horizontalPadding = fontSize * 0.1;
    var topMargin = fontSize * 1.5;
    var baseline = topMargin;
    var x = horizontalPadding;
    var newPaths = [];

    for (var c = 0; c < text.length; c++) {
      var char = text[c];
      var glyph = font.charToGlyph(char);
      var path = glyph.getPath(x, baseline, fontSize);
      newPaths.push(path.toPathData(3));
      var advanceWidth = glyph.advanceWidth ?? font.unitsPerEm;
      x += advanceWidth * (fontSize / font.unitsPerEm);
    }

    return {
      width: Math.ceil(x + horizontalPadding),
      height: Math.ceil(fontSize * 3),
      fontSize: fontSize,
      paths: newPaths
    };
  }

  function createSignatureSVG(options) {
    options = options || {};
    var paths = options.paths || [];
    var width = options.width || 502;
    var height = options.height || 108;
    var viewBox = options.viewBox || ('0 0 ' + width + ' ' + height);
    var fontSize = options.fontSize || 21;
    var color = options.color || '#050505';
    var className = options.className || '';

    var maskId = 'signature-reveal-' + Math.random().toString(36).substring(2, 9);
    var strokeWidth = fontSize * 0.22;

    var svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('width', width);
    svg.setAttribute('height', height);
    svg.setAttribute('viewBox', viewBox);
    svg.setAttribute('fill', 'none');
    svg.setAttribute('class', ('signature-svg ' + className).trim());
    svg.style.overflow = 'visible';

    // 1. Defs & Mask
    var defs = document.createElementNS('http://www.w3.org/2000/svg', 'defs');
    var mask = document.createElementNS('http://www.w3.org/2000/svg', 'mask');
    mask.setAttribute('id', maskId);
    mask.setAttribute('maskUnits', 'userSpaceOnUse');

    var maskPaths = [];
    for (var i = 0; i < paths.length; i++) {
      var d = paths[i];
      var p = document.createElementNS('http://www.w3.org/2000/svg', 'path');
      p.setAttribute('d', d);
      p.setAttribute('stroke', 'white');
      p.setAttribute('stroke-width', strokeWidth);
      p.setAttribute('fill', 'none');
      p.setAttribute('vector-effect', 'non-scaling-stroke');
      p.setAttribute('stroke-linecap', 'round');
      p.setAttribute('stroke-linejoin', 'round');
      mask.appendChild(p);
      maskPaths.push(p);
    }
    defs.appendChild(mask);
    svg.appendChild(defs);

    // 2. Visible Outline Strokes
    var strokePaths = [];
    for (var j = 0; j < paths.length; j++) {
      var dStroke = paths[j];
      var pStroke = document.createElementNS('http://www.w3.org/2000/svg', 'path');
      pStroke.setAttribute('d', dStroke);
      pStroke.setAttribute('stroke', color);
      pStroke.setAttribute('stroke-width', '2');
      pStroke.setAttribute('fill', 'none');
      pStroke.setAttribute('vector-effect', 'non-scaling-stroke');
      pStroke.setAttribute('stroke-linecap', 'butt');
      pStroke.setAttribute('stroke-linejoin', 'round');
      svg.appendChild(pStroke);
      strokePaths.push(pStroke);
    }

    // 3. Masked Solid Fill
    var fillGroup = document.createElementNS('http://www.w3.org/2000/svg', 'g');
    fillGroup.setAttribute('mask', 'url(#' + maskId + ')');
    for (var k = 0; k < paths.length; k++) {
      var dFill = paths[k];
      var pFill = document.createElementNS('http://www.w3.org/2000/svg', 'path');
      pFill.setAttribute('d', dFill);
      pFill.setAttribute('fill', color);
      fillGroup.appendChild(pFill);
    }
    svg.appendChild(fillGroup);

    return { svg: svg, maskPaths: maskPaths, strokePaths: strokePaths };
  }

  function animateSignature(options) {
    options = options || {};
    var maskPaths = options.maskPaths || [];
    var strokePaths = options.strokePaths || [];
    var duration = options.duration !== undefined ? options.duration : 0.85;
    var delay = options.delay !== undefined ? options.delay : 0;
    var onComplete = options.onComplete;

    var gsapLib = (typeof window !== 'undefined' && window.gsap) ? window.gsap : null;
    if (!gsapLib) {
      if (typeof onComplete === 'function') {
        setTimeout(onComplete, (delay + maskPaths.length * 0.085 + duration) * 1000);
      }
      return null;
    }

    var tl = gsapLib.timeline({
      onComplete: function() {
        if (typeof onComplete === 'function') onComplete();
      }
    });

    for (var i = 0; i < maskPaths.length; i++) {
      var maskP = maskPaths[i];
      var strokeP = strokePaths[i];
      var d = maskP.getAttribute('d');
      if (!d || d.trim() === '') continue;

      var len = 0;
      try {
        len = maskP.getTotalLength() || 0;
      } catch (e) {
        len = 0;
      }

      if (len <= 0) continue;

      // Set initial hidden state
      gsapLib.set([maskP, strokeP], {
        strokeDasharray: len + 2,
        strokeDashoffset: len + 2,
        opacity: 0
      });

      var charStart = delay + i * 0.085;

      // Opacity reveal at delay + 0.01
      tl.to([maskP, strokeP], {
        opacity: 1,
        duration: 0.01,
        ease: 'none'
      }, charStart + 0.01);

      // Path stroke drawing over duration seconds
      tl.to([maskP, strokeP], {
        strokeDashoffset: 0,
        duration: duration,
        ease: 'power2.inOut'
      }, charStart);
    }

    return tl;
  }

