    var tl = animateSignature({
      maskPaths: result.maskPaths,
      strokePaths: result.strokePaths,
      duration: duration,
      delay: delay,
      onComplete: onComplete
    });

    if (typeof window !== 'undefined') {
      window.__sigTimeline = tl;
    }

    return { svg: result.svg, timeline: tl };
